"""ER Editor — редактор инфологических (нотация Баркера) и даталогических моделей баз данных.

Пакет читает схему SQLite, строит по ней две диаграммы и позволяет править их мышью и
клавиатурой в окне pygame, а затем экспортировать в PNG. Схему можно нарисовать с нуля, проверить
на соответствие нормальной форме и скачать как базу данных SQLite вместе с обеими моделями. Подробное руководство — в
``README.md`` в корне проекта (его же показывает кнопка «О программе»).

Модули:
    model   — модель данных (проект, диаграммы, узлы, связи, легенда); без зависимости от pygame.
    geom    — геометрия: прямоугольники, ортогональные маршруты связей, попадание курсора.
    layout  — автораскладка узлов и подбор маршрутов связей.
    schema  — чтение схемы SQLite и построение начальных диаграмм.
    dbgen   — создание базы данных SQLite по даталогической диаграмме и случайные данные.
    normalform — проверка нарисованной схемы на 1НФ, 2НФ, 3НФ и НФБК (только проверка, схема не меняется).
    render  — шрифты, графический контекст, сцена, отрисовка и экспорт PNG.
    ui      — текстовый редактор, буфер обмена, системные диалоги выбора файла.
    markdown — мини-рендерер Markdown для окна «О программе».
    app     — главное окно: события, панель свойств, undo/redo, файлы.
"""

